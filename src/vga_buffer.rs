// VGA-like colors (32-bit RGB)
#[allow(dead_code)]
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
#[repr(u32)]
pub enum Color {
    Black = 0x000000,
    Blue = 0x0000AA,
    Green = 0x00AA00,
    Cyan = 0x00AAAA,
    Red = 0xAA0000,
    Magenta = 0xAA00AA,
    Brown = 0xAA5500,
    LightGray = 0xAAAAAA,
    DarkGray = 0x555555,
    LightBlue = 0x5555FF,
    LightGreen = 0x55FF55,
    LightCyan = 0x55FFFF,
    LightRed = 0xFF5555,
    Pink = 0xFF55FF,
    Yellow = 0xFFFF55,
    White = 0xFFFFFF,
}

pub struct Writer {
    framebuffer: &'static mut [u8],
    info: FrameBufferInfo,
    x_pos: usize,
    y_pos: usize,
    fg_color: u32,
    bg_color: u32,
    scale: usize,
}

impl Writer {
    pub fn new(framebuffer: &'static mut [u8], info: FrameBufferInfo) -> Self {
        let mut writer = Writer {
            framebuffer,
            info,
            x_pos: 0,
            y_pos: 0,
            fg_color: Color::White as u32,
            bg_color: Color::Black as u32,
            scale: 2,
        };
        writer.clear_screen();
        writer
    }

    pub fn info(&self) -> FrameBufferInfo {
        self.info
    }

    fn write_pixel(&mut self, x: usize, y: usize, color: u32) {
        if x >= self.info.width || y >= self.info.height {
            return;
        }

        let pixel_offset = y * self.info.stride + x;
        let color_bytes = color.to_le_bytes();
        let bytes_per_pixel = self.info.bytes_per_pixel;
        let byte_offset = pixel_offset * bytes_per_pixel;

        match self.info.pixel_format {
            PixelFormat::Rgb => {
                if byte_offset + 2 < self.framebuffer.len() {
                    self.framebuffer[byte_offset] = color_bytes[0];
                    self.framebuffer[byte_offset + 1] = color_bytes[1];
                    self.framebuffer[byte_offset + 2] = color_bytes[2];
                }
            }
            PixelFormat::Bgr => {
                if byte_offset + 2 < self.framebuffer.len() {
                    self.framebuffer[byte_offset] = color_bytes[2];
                    self.framebuffer[byte_offset + 1] = color_bytes[1];
                    self.framebuffer[byte_offset + 2] = color_bytes[0];
                }
            }
            PixelFormat::U8 => {
                if byte_offset < self.framebuffer.len() {
                    self.framebuffer[byte_offset] = color_bytes[0];
                }
            }
            _ => {}
        }
    }

    pub fn draw_rect(&mut self, x: usize, y: usize, width: usize, height: usize, color: u32) {
        for dy in 0..height {
            for dx in 0..width {
                self.write_pixel(x + dx, y + dy, color);
            }
        }
    }

    pub fn draw_char_at(&mut self, x: usize, y: usize, c: char, color: u32, scale: usize) {
        let glyph_idx = (c as usize).saturating_sub(32);
        if glyph_idx < FONT.len() {
            let glyph = FONT[glyph_idx];
            for (row, byte) in glyph.iter().enumerate() {
                for col in 0..8 {
                    if (byte & (0x80 >> col)) != 0 {
                        for dy in 0..scale {
                            for dx in 0..scale {
                                self.write_pixel(x + col * scale + dx, y + row * scale + dy, color);
                            }
                        }
                    }
                }
            }
        }
    }

    pub fn write_char(&mut self, c: char) {
        match c {
            '\n' => self.newline(),
            '\x08' => self.backspace(),
            _ => {
                let char_width = 8 * self.scale;
                let char_height = 8 * self.scale;

                if self.x_pos + char_width >= self.info.width {
                    self.newline();
                }
                if self.y_pos + char_height >= self.info.height {
                    self.scroll();
                }

                let glyph_idx = (c as usize).saturating_sub(32);
                if glyph_idx < FONT.len() {
                    let glyph = FONT[glyph_idx];
                    for (row, byte) in glyph.iter().enumerate() {
                        for col in 0..8 {
                            let color = if (byte & (0x80 >> col)) != 0 {
                                self.fg_color
                            } else {
                                self.bg_color
                            };
                            
                            // Draw scaled pixel
                            for dy in 0..self.scale {
                                for dx in 0..self.scale {
                                    self.write_pixel(self.x_pos + col * self.scale + dx, self.y_pos + row * self.scale + dy, color);
                                }
                            }
                        }
                    }
                }
                self.x_pos += char_width;
            }
        }
    }

    fn newline(&mut self) {
        self.x_pos = 0;
        self.y_pos += 8 * self.scale;
        if self.y_pos + 8 * self.scale >= self.info.height {
            self.scroll();
        }
    }

    fn backspace(&mut self) {
        let char_width = 8 * self.scale;
        let char_height = 8 * self.scale;

        if self.x_pos >= char_width {
            self.x_pos -= char_width;
            for row in 0..char_height {
                for col in 0..char_width {
                    self.write_pixel(self.x_pos + col, self.y_pos + row, self.bg_color);
                }
            }
        }
    }

    fn scroll(&mut self) {
        // Simple scroll by clearing screen if it's too much (robust for now)
        if self.y_pos + 16 * self.scale >= self.info.height {
            self.clear_screen();
        }
    }

    pub fn clear_screen(&mut self) {
        for i in 0..self.framebuffer.len() {
            self.framebuffer[i] = 0;
        }
        self.x_pos = 0;
        self.y_pos = 0;
    }

    pub fn set_color(&mut self, fg: Color, bg: Color) {
        self.fg_color = fg as u32;
        self.bg_color = bg as u32;
    }

    pub fn update_cursor(&self) {}
    pub fn enable_cursor(&self) {}
}

impl fmt::Write for Writer {
    fn write_str(&mut self, s: &str) -> fmt::Result {
        for c in s.chars() {
            self.write_char(c);
        }
        Ok(())
    }
}

pub struct LockedWriter(Option<Writer>);

impl LockedWriter {
    pub const fn empty() -> Self {
        LockedWriter(None)
    }

    pub fn init(&mut self, framebuffer: &'static mut [u8], info: FrameBufferInfo) {
        self.0 = Some(Writer::new(framebuffer, info));
    }

    pub fn lock(&mut self) -> &mut Writer {
        self.0.as_mut().expect("Writer not initialized")
    }

    pub fn clear_screen(&mut self) {
        if let Some(ref mut w) = self.0 {
            w.clear_screen();
        }
    }

    pub fn set_color(&mut self, fg: Color, bg: Color) {
        if let Some(ref mut w) = self.0 {
            w.set_color(fg, bg);
        }
    }

    pub fn update_cursor(&self) {
        if let Some(ref w) = self.0 {
            w.update_cursor();
        }
    }

    pub fn enable_cursor(&self) {
        if let Some(ref w) = self.0 {
            w.enable_cursor();
        }
    }

    pub fn get_mut(&mut self) -> Option<&mut Writer> {
        self.0.as_mut()
    }
}

pub static WRITER: Mutex<LockedWriter> = Mutex::new(LockedWriter::empty());

#[macro_export]
macro_rules! print {
    ($($arg:tt)*) => ($crate::vga_buffer::_print(format_args!($($arg)*)));
}

#[macro_export]
macro_rules! println {
    () => ($crate::print!("\n"));
    ($($arg:tt)*) => ($crate::print!("{}\n", format_args!($($arg)*)));
}

#[doc(hidden)]
pub fn _print(args: fmt::Arguments) {
    use core::fmt::Write;
    use x86_64::instructions::interrupts;

    interrupts::without_interrupts(|| {
        let mut writer = WRITER.lock();
        if writer.0.is_some() {
            writer.lock().write_fmt(args).unwrap();
        }
    });
}

pub fn print_colored(s: &str, fg: Color, bg: Color) {
    use x86_64::instructions::interrupts;
    use core::fmt::Write;

    interrupts::without_interrupts(|| {
        let mut locked = WRITER.lock();
        if let Some(ref mut writer) = locked.0 {
            let old_fg = writer.fg_color;
            let old_bg = writer.bg_color;
            writer.fg_color = fg as u32;
            writer.bg_color = bg as u32;
            writer.write_str(s).unwrap();
            writer.fg_color = old_fg;
            writer.bg_color = old_bg;
        }
    });
}
